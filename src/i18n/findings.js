/** Resolve a finding to display text in the active locale. */
export function describe(finding, locale) {
  const dict = findingText[locale] || findingText.EN;
  const tpl = dict[finding.code] || findingText.EN[finding.code] || finding.code;
  return tpl.replace("{v}", finding.v ?? "");
}

export default findingText;
